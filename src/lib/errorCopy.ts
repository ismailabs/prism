export function userError(error: unknown, locale: Locale): string {
  const value = error && typeof error === 'object' ? error as { message?: unknown; code?: unknown } : {};
  if (typeof value.code === 'string' && Object.hasOwn(auth, value.code)) return auth[value.code][locale === 'ms' ? 1 : 0];
  const message = typeof value.message === 'string' ? value.message : '';
  if (message === 'PRISM_OFFLINE') return locale === 'ms' ? messages[message] : 'You are offline. Reconnect to continue. No changes are queued.';
  if (Object.hasOwn(messages, message)) return locale === 'ms' ? messages[message] : message;
  const precision = /^(MYR|USD|EUR|JPY) allows (0|2) decimal places; amounts are never rounded silently\.$/.exec(message);
  if (precision) return locale === 'ms' ? `${precision[1]} membenarkan ${precision[2]} tempat perpuluhan; amaun tidak dibundarkan secara senyap.` : message;
  if (Object.values(messages).includes(message)) return message;
  return locale === 'ms' ? 'Permintaan tidak dapat diselesaikan. Cuba lagi. Jika anda sedang menyimpan, semak rekod anda dahulu.' : 'The request could not be completed. Try again. If you were saving, check your records first.';
}
